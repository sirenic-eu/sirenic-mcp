/** The README tools table, derived from the snapshot: shared by `npm run tableau` and its test. */
import type { Tool } from "@modelcontextprotocol/sdk/types.js";
import { routePrices } from "../src/catalogue.js";
import { formatUsd, parseUsd } from "../src/money.js";
import type { Snapshot } from "../src/snapshot.js";

export const TABLE_START = "<!-- tools:start (generated by npm run tableau, do not edit) -->";
export const TABLE_END = "<!-- tools:end -->";

/** A tool's price as the server states it in `_meta`: one figure, a range, "per entity", or free. */
export function priceLabel(tool: Tool): string {
  const prices = routePrices(tool);
  if (!prices) return "in the quote";
  const routes = Object.values(prices);
  if (routes.length === 0) return "free";
  const amounts = routes.map((r) => parseUsd(r.prix)).filter((a): a is bigint => a !== undefined);
  if (amounts.length !== routes.length) return "in the quote";
  const low = amounts.reduce((a, b) => (b < a ? b : a));
  const high = amounts.reduce((a, b) => (b > a ? b : a));
  const perEntity = routes.every((r) => r.par === "entite") ? " per entity" : "";
  return low === high ? `${formatUsd(low)}${perEntity}` : `${formatUsd(low)} to ${formatUsd(high)}${perEntity}`;
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

export function toolsTable(snapshot: Snapshot): string {
  const tools = [...snapshot.tools].sort((a, b) => a.name.localeCompare(b.name));
  const paid = tools.filter((t) => {
    const p = routePrices(t);
    return p === undefined || Object.keys(p).length > 0;
  }).length;
  const date = snapshot.generated_at.slice(0, 10);
  // The European countries other than France, read in the routes the server declares (/v1/eu/entreprise/XX/...).
  const countries = new Set<string>();
  for (const t of tools) {
    const routes = t._meta?.["eu.sirenic/routes"];
    for (const r of Array.isArray(routes) ? routes : []) {
      const m = /\/v1\/eu\/entreprise\/([A-Z]{2})\//.exec(String(r));
      if (m) countries.add(m[1]!);
    }
  }
  const coverage = countries.size > 0 ? ` covering France and ${countries.size} other European countries` : "";
  const lines = [
    `${tools.length} tools (${paid} paid, ${tools.length - paid} free)${coverage}, read from the Sirenic server ${snapshot.server.version} on ${date}. Prices are in USD per call (per entity for batch tools), the same by API key and by x402.`,
    "",
    "| Tool | What it does | Price |",
    "|---|---|---|",
    ...tools.map((t) => `| \`${t.name}\` | ${cell(t.title ?? t.annotations?.title ?? "")} | ${priceLabel(t)} |`),
  ];
  return lines.join("\n");
}

export function replaceToolsTable(readme: string, snapshot: Snapshot): string {
  const start = readme.indexOf(TABLE_START);
  const end = readme.indexOf(TABLE_END);
  if (start < 0 || end < start) throw new Error("README.md has no tools table markers");
  return `${readme.slice(0, start + TABLE_START.length)}\n\n${toolsTable(snapshot)}\n\n${readme.slice(end)}`;
}
