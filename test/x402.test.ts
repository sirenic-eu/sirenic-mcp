/**
 * The x402 rail (letters M4 A and M5 A, decision C): the API answers a paid route without payment with a 402 whose quote
 * is in PAYMENT-REQUIRED; the local wallet signs it under the cap per call (0.05 by default) and the session cap (0.50 by
 * default) and sends the same request again with PAYMENT-SIGNATURE. Above a cap, an explicit refusal with the quoted price
 * and the variable to raise. The API's receipt reaches the client. Nothing is ever replayed.
 *
 * After a signature (M1 of the review of 18/10/2026, decision A): a settlement the API could not confirm, a 402 that is
 * neither a quote nor a settlement outcome, an answer that is not the API's, a broken connection or a call cancelled
 * while the payment travels all count the price against the session cap (reglement_incertain); a refused settlement, a new
 * quote and an error of the API give it back. Cancellation (m4): before the signed request is sent, nothing is paid.
 *
 * Wallet: a throwaway key generated by the test (no funds); the quotes are the ones the API served on 2026-11-19.
 */
import { decodePaymentSignatureHeader } from "@x402/core/http";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { afterEach, describe, expect, it } from "vitest";
import type { ApiReply, ApiRequest } from "./helpers/fake-api.js";
import { DEVIS, dataReply, errorReply, paymentResponseHeader, quoteReply, recordedQuote } from "./helpers/fixtures.js";
import { localServer, resultOf } from "./helpers/local.js";

const KEY = generatePrivateKey();
const PAYER = privateKeyToAccount(KEY).address;
const RECEIPT = { success: true, transaction: `0x${"ab".repeat(32)}`, network: "eip155:8453", payer: PAYER };
const SEARCH = { name: "search_french_companies", arguments: { q: "danone" } };
const RISK = { name: "get_french_company_default_risk", arguments: { siren: "552032534" } };
const USDC = "0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913";

let close: (() => Promise<void>) | undefined;
afterEach(async () => {
  await close?.();
  close = undefined;
});

const signedOf = (q: ApiRequest): string | undefined => q.headers["payment-signature"];

/** The API: the recorded quote without payment, then `paid(n)` for the n-th signed request. */
function api(quote: "search_french_companies" | "get_french_company_default_risk", paid: (n: number) => ApiReply | Promise<ApiReply>) {
  let n = 0;
  return { onRequest: (q: ApiRequest): ApiReply | Promise<ApiReply> => (signedOf(q) ? paid(++n) : quoteReply(quote)) };
}

describe("x402 rail", () => {
  it("a $0.002 quote is signed locally, the same request is sent again with PAYMENT-SIGNATURE, the API's receipt reaches the client", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => dataReply({ resultats: [] }, { "payment-response": paymentResponseHeader(RECEIPT) })));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(r.isError).toBe(false);
    expect(r._meta?.["x402/payment-response"]).toEqual(RECEIPT);
    const [first, second] = t.api.requests;
    expect(t.api.requests.length).toBe(2);
    expect(first!.path).toBe(DEVIS.answers.search_french_companies.request.path);
    expect(second!.path).toBe(first!.path);
    expect(second!.headers.accept).toBe(first!.headers.accept);
    expect(signedOf(first!)).toBeUndefined();
    const payload = decodePaymentSignatureHeader(signedOf(second!)!);
    expect(payload.accepted.amount).toBe("2000");
    expect(payload.accepted.asset).toBe(USDC); // EURC needs an explicit opt-in
    expect((payload.payload as { authorization: { from: string } }).authorization.from).toBe(PAYER);
    expect(t.local.spent).toBe(2000n);
    for (const q of t.api.requests) {
      expect(q.headers["x-api-key"]).toBeUndefined();
      expect(q.headers["user-agent"]).toMatch(/^sirenic-mcp-npm\//);
    }
  });

  it("the receipt is the API's only: a paid answer without one returns none, nor does a refusal by the cap", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, { onRequest: (q) => (signedOf(q) ? dataReply() : quoteReply(q.path.startsWith("/v1/recherche") ? "search_french_companies" : "get_french_company_default_risk")) });
    close = t.close;
    const paid = await t.client.callTool(SEARCH);
    expect(paid.isError).toBe(false);
    expect(t.local.spent).toBe(2000n);
    expect(paid._meta?.["x402/payment-response"]).toBeUndefined();
    const capped = await t.client.callTool(RISK);
    expect(resultOf(capped).error).toBe("plafond_depasse");
    expect(capped._meta?.["x402/payment-response"]).toBeUndefined();
  });

  it("a $0.10 quote is above the $0.05 cap per call: plafond_depasse with the price and the variable, nothing signed", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("get_french_company_default_risk", () => dataReply()));
    close = t.close;
    const r = await t.client.callTool(RISK);
    expect(r.isError).toBe(true);
    expect(resultOf(r)).toMatchObject({ error: "plafond_depasse", price_usd: "$0.10", cap_usd: "$0.05", variable: "SIRENIC_MAX_PAR_APPEL" });
    expect(resultOf(r).message).toContain("SIRENIC_MAX_PER_CALL");
    expect(t.api.requests.length).toBe(1);
    expect(t.local.spent).toBe(0n);
  });

  it("raising SIRENIC_MAX_PAR_APPEL (or its alias) lets the same quote through", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PER_CALL: "0.10" }, api("get_french_company_default_risk", () => dataReply()));
    close = t.close;
    const r = await t.client.callTool(RISK);
    expect(r.isError).toBe(false);
    expect(t.local.spent).toBe(100000n);
    expect(decodePaymentSignatureHeader(signedOf(t.api.requests[1]!)!).accepted.amount).toBe(recordedQuote("get_french_company_default_risk").accepts[0]!.amount);
  });

  it("the session cap: three $0.002 calls under a $0.005 session cap, the third is refused with SIRENIC_MAX_PAR_SESSION", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.005" }, api("search_french_companies", () => dataReply()));
    close = t.close;
    for (let i = 0; i < 2; i++) expect((await t.client.callTool(SEARCH)).isError).toBe(false);
    const third = await t.client.callTool(SEARCH);
    expect(resultOf(third)).toMatchObject({ error: "plafond_depasse", price_usd: "$0.002", cap_usd: "$0.005", session_spent_usd: "$0.004", variable: "SIRENIC_MAX_PAR_SESSION" });
    expect(t.local.spent).toBe(4000n);
    expect(t.api.requests.filter(signedOf).length).toBe(2);
  });

  it("five calls at once, $0.002 each, under a $0.005 session cap: reserved before signing, two signed, never more than the cap", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.005" }, api("search_french_companies", () => dataReply()));
    close = t.close;
    const results = await Promise.all(Array.from({ length: 5 }, () => t.client.callTool(SEARCH)));
    expect(t.api.requests.filter(signedOf).length).toBe(2);
    expect(t.local.spent).toBe(4000n);
    const refused = results.filter((r) => r.isError).map(resultOf);
    expect(refused.length).toBe(3);
    for (const e of refused) expect(e).toMatchObject({ error: "plafond_depasse", cap_usd: "$0.005", variable: "SIRENIC_MAX_PAR_SESSION" });
  });

  it("a reservation is given back when the payment does not go through (API error, new quote, refused settlement, 429): the next call is signed", async () => {
    // a $0.002 session cap: room for exactly one payment, so a reservation kept by mistake refuses the next call
    const answers: ApiReply[] = [
      errorReply(503, { error: "amont_indisponible", message: "Upstream register unavailable" }),
      quoteReply("search_french_companies"),
      errorReply(402, { x402Version: 2, error: "reglement_refuse", message: "refused", settlement: { outcome: "refuse", transaction: null, network: null, attempts: [] } }),
      errorReply(429, { error: "trop_de_requetes", message: "Slow down" }),
      dataReply(),
    ];
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.002" }, api("search_french_companies", (n) => answers[n - 1]!));
    close = t.close;
    expect(resultOf(await t.client.callTool(SEARCH))).toMatchObject({ statut_http: 503, error: "amont_indisponible" });
    expect(resultOf(await t.client.callTool(SEARCH)).error).toBe("paiement_refuse");
    expect(resultOf(await t.client.callTool(SEARCH)).error).toBe("paiement_refuse");
    expect(resultOf(await t.client.callTool(SEARCH))).toMatchObject({ statut_http: 429, error: "trop_de_requetes" });
    expect((await t.client.callTool(SEARCH)).isError).toBe(false);
    expect(t.local.spent).toBe(2000n);
    expect(t.api.requests.filter(signedOf).length).toBe(5);
  });

  it("a new quote after the payment: paiement_refuse with its reason, nothing replayed, nothing counted", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => quoteReply("search_french_companies")));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(resultOf(r).error).toBe("paiement_refuse");
    expect(t.api.requests.length).toBe(2);
    expect(t.local.spent).toBe(0n);
  });

  it("an error of the API after the payment reaches the client as served and is not counted (an error cancels the payment)", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => errorReply(503, { error: "amont_indisponible", message: "Upstream register unavailable" })));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(resultOf(r)).toEqual({ statut_http: 503, error: "amont_indisponible", message: "Upstream register unavailable" });
    expect(r.isError).toBe(true);
    expect(t.local.spent).toBe(0n);
  });
});

describe("M1: after a signature, an outcome that may have paid counts against the session cap", () => {
  const uncertainCases: Array<[string, ApiReply]> = [
    ["a settlement the API could not confirm (reglement_indetermine)", errorReply(402, { x402Version: 2, error: "reglement_indetermine", message: "may have been settled", settlement: { outcome: "indetermine", transaction: `0x${"cd".repeat(32)}`, network: "eip155:8453", attempts: [] } })],
    ["a new quote saying the authorization was already used on chain", (() => {
      const q = recordedQuote("search_french_companies") as Record<string, unknown>;
      return { status: 402, json: { error: "payment_required" }, headers: { "payment-required": Buffer.from(JSON.stringify({ ...q, error: "invalid_exact_evm_nonce_already_used" })).toString("base64") } };
    })()],
    ["a 402 that is neither a quote nor a settlement outcome", errorReply(402, { error: "autre_chose" })],
    ["a page of the front server (502)", { status: 502, text: "<html>Bad Gateway</html>", contentType: "text/html" }],
    ["a gateway timeout (504) without body", { status: 504 }],
    ["JSON without an error code (500)", errorReply(500, { oops: true })],
    ["a broken connection", { networkError: "socket hang up" }],
  ];

  it.each(uncertainCases)("%s: reglement_incertain, the price counted, nothing replayed", async (_title, reply) => {
    // a $0.002 session cap: once counted, the next call is refused by the cap
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.002" }, api("search_french_companies", () => reply));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(r.isError).toBe(true);
    expect(resultOf(r)).toMatchObject({ error: "reglement_incertain", price_usd: "$0.002" });
    expect(t.local.spent).toBe(2000n);
    expect(t.api.requests.length).toBe(2);
    const next = await t.client.callTool(SEARCH);
    expect(resultOf(next).error).toBe("plafond_depasse");
    expect(t.api.requests.filter(signedOf).length).toBe(1);
  });

  it("a refusal body that is not consistent (no outcome, no attempts) is undetermined: counted", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => errorReply(402, { x402Version: 2, error: "reglement_refuse", message: "refused" })));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(resultOf(r).error).toBe("reglement_incertain");
    expect(t.local.spent).toBe(2000n);
  });

  it("the transaction of an undetermined settlement is passed on", async () => {
    const tx = `0x${"cd".repeat(32)}`;
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => uncertainCases[0]![1]));
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(resultOf(r)).toMatchObject({ error: "reglement_incertain", transaction: tx, statut_http: 402 });
  });
});

describe("only USDC on Base is signed", () => {
  const withOptions = (accepts: unknown[]): ApiReply => {
    const q = recordedQuote("search_french_companies");
    return { status: 402, json: { error: "payment_required" }, headers: { "payment-required": Buffer.from(JSON.stringify({ ...q, accepts })).toString("base64") } };
  };
  const usdc = () => structuredClone(recordedQuote("search_french_companies").accepts.find((a) => a.asset.toLowerCase() === USDC.toLowerCase())!);

  it.each([
    ["another chain (Base Sepolia)", () => [{ ...usdc(), network: "eip155:84532" }]],
    ["another token on Base", () => [{ ...usdc(), asset: "0x0000000000000000000000000000000000000001" }]],
    ["EURC only (needs an opt-in this package does not give)", () => [{ ...usdc(), asset: "0x60a3E35Cc302bFA44Cb288Bc5a4F316Fdb1adb42" }]],
    ["another scheme", () => [{ ...usdc(), scheme: "upto" }]],
  ])("%s: paiement_refuse, nothing signed, nothing counted", async (_title, accepts) => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, { onRequest: (q) => (signedOf(q) ? dataReply() : withOptions(accepts())) });
    close = t.close;
    const r = await t.client.callTool(SEARCH);
    expect(resultOf(r).error).toBe("paiement_refuse");
    expect(resultOf(r).message).toContain("USDC on Base");
    expect(t.api.requests.filter(signedOf)).toEqual([]);
    expect(t.local.spent).toBe(0n);
  });

  it("a quote with a foreign option next to USDC on Base: the USDC option is signed, at its price", async () => {
    const accepts = [{ ...usdc(), network: "eip155:84532", amount: "1" }, usdc()];
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, { onRequest: (q) => (signedOf(q) ? dataReply() : withOptions(accepts)) });
    close = t.close;
    expect((await t.client.callTool(SEARCH)).isError).toBe(false);
    const payload = decodePaymentSignatureHeader(signedOf(t.api.requests[1]!)!);
    expect(payload.accepted.network).toBe("eip155:8453");
    expect(payload.accepted.amount).toBe("2000");
    expect(t.local.spent).toBe(2000n);
  });
});

describe("m4: the client's cancellation follows the call", () => {
  /** The local server's wallet, wrapped: `before` runs at the start of each signature. */
  function wrapSign(local: unknown, before: () => void): { signed: () => number } {
    const wallet = (local as { wallet: { sign: (...a: unknown[]) => Promise<unknown> } }).wallet;
    const sign = wallet.sign.bind(wallet);
    let n = 0;
    wallet.sign = async (...a: unknown[]) => {
      before();
      n++;
      return sign(...a);
    };
    return { signed: () => n };
  }

  it("cancelled while the quote is being signed: appel_annule, the signature never sent, nothing held, the next call goes through", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.002" }, api("search_french_companies", () => dataReply()));
    close = t.close;
    const controller = new AbortController();
    const hook = wrapSign(t.local, () => controller.abort());
    const r = await t.local.call(SEARCH.name, SEARCH.arguments, controller.signal);
    expect(resultOf(r).error).toBe("appel_annule");
    expect(hook.signed()).toBe(1);
    expect(t.api.requests.filter(signedOf)).toEqual([]);
    expect(t.local.spent).toBe(0n);
    expect((t.local as unknown as { wallet: { reserved: bigint } }).wallet.reserved).toBe(0n);
    // nothing was held: the session cap of $0.002 still has room for one payment
    expect((await t.client.callTool(SEARCH)).isError).toBe(false);
    expect(t.local.spent).toBe(2000n);
  });

  it("cancelled once the quote is back, before the signature: the wallet never signs", async () => {
    const controller = new AbortController();
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, api("search_french_companies", () => dataReply()));
    close = t.close;
    const hook = wrapSign(t.local, () => undefined);
    // the quote is delivered and checked against the caps; the client leaves right then, before the package signs
    const wallet = (t.local as unknown as { wallet: { decide: (...a: unknown[]) => unknown } }).wallet;
    const decide = wallet.decide.bind(wallet);
    wallet.decide = (...a: unknown[]) => {
      const decision = decide(...a);
      controller.abort();
      return decision;
    };
    const r = await t.local.call(SEARCH.name, SEARCH.arguments, controller.signal);
    expect(resultOf(r).error).toBe("appel_annule");
    expect(t.api.requests.filter(signedOf)).toEqual([]);
    expect(hook.signed()).toBe(0);
    expect(t.local.spent).toBe(0n);
  });

  it("cancelled while the first request is in flight: appel_annule, nothing reserved, nothing signed", async () => {
    const controller = new AbortController();
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, {
      onRequest: () => {
        setTimeout(() => controller.abort(), 10);
        return { hang: true };
      },
    });
    close = t.close;
    await expect(t.client.callTool(SEARCH, undefined, { signal: controller.signal })).rejects.toThrow();
    await new Promise((r) => setTimeout(r, 50));
    expect(t.api.requests.length).toBe(1);
    expect(t.local.spent).toBe(0n);
  });

  it("cancelled when the quote comes back, before the signature is sent: nothing signed, nothing counted", async () => {
    const controller = new AbortController();
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, {
      onRequest: (q) => {
        if (signedOf(q)) return dataReply();
        controller.abort();
        return quoteReply("search_french_companies");
      },
    });
    close = t.close;
    await expect(t.client.callTool(SEARCH, undefined, { signal: controller.signal })).rejects.toThrow();
    await new Promise((r) => setTimeout(r, 50));
    expect(t.api.requests.filter(signedOf)).toEqual([]);
    expect(t.local.spent).toBe(0n);
  });

  it("cancelled while the signed request is in flight: the request is cut and the payment counts as uncertain", async () => {
    const controller = new AbortController();
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY, SIRENIC_MAX_PAR_SESSION: "0.002" }, {
      onRequest: (q) => {
        if (!signedOf(q)) return quoteReply("search_french_companies");
        setTimeout(() => controller.abort(), 10);
        return { hang: true };
      },
    });
    close = t.close;
    await expect(t.client.callTool(SEARCH, undefined, { signal: controller.signal })).rejects.toThrow();
    await new Promise((r) => setTimeout(r, 50));
    expect(t.api.requests.filter(signedOf).length).toBe(1);
    expect(t.local.spent).toBe(2000n);
    // counted: the cap refuses the next call
    expect(resultOf(await t.client.callTool(SEARCH)).error).toBe("plafond_depasse");
  });

  it("the server side: a call cancelled before sending answers appel_annule, nothing sent", async () => {
    const t = await localServer({ SIRENIC_WALLET_KEY: KEY }, { onRequest: () => dataReply() });
    close = t.close;
    const controller = new AbortController();
    controller.abort();
    const r = await t.local.call("search_french_companies", { q: "danone" }, controller.signal);
    expect(resultOf(r).error).toBe("appel_annule");
    expect(t.api.requests).toEqual([]);
  });
});

describe("no rail", () => {
  it("a quote comes back as paiement_requis: the quote, the free key offer, and how to pay; isError false, schema kept", async () => {
    const t = await localServer({}, { onRequest: () => quoteReply("search_french_companies") });
    close = t.close;
    // the in-memory client validates structured content against the tool's output schema: a mismatch would throw here
    const r = await t.client.callTool(SEARCH);
    expect(r.isError).toBe(false);
    const s = r.structuredContent as { payment_required: boolean; hint: string; quote: { accepts: unknown[] }; free_tier: { signup_url: string; summary: string } };
    expect(s.payment_required).toBe(true);
    expect(s.quote).toEqual(recordedQuote("search_french_companies"));
    expect(s.free_tier).toEqual(DEVIS.answers.search_french_companies.body.free_tier);
    expect(s.free_tier.signup_url).toContain("utm_campaign=mcp-npm");
    expect(s.hint).toContain("paiement_requis: this tool costs $0.002 per call.");
    expect(s.hint).toContain(s.free_tier.summary);
    expect(s.hint).toContain("SIRENIC_API_KEY");
    expect(s.hint).toContain("SIRENIC_WALLET_KEY");
    expect(t.api.requests.length).toBe(1);
    expect(r._meta?.["x402/payment-response"]).toBeUndefined();
  });

  it("the hint keeps the API's word on the free tier: a route outside it is not offered as free", async () => {
    const quote = quoteReply("get_french_company_default_risk") as { status: number; json: Record<string, unknown>; headers: Record<string, string> };
    const outside = { ...quote, json: { ...quote.json, free_tier: { summary: "Free API key, no card: not this route.", this_route: false, signup_url: "https://api.sirenic.eu/compte" } } };
    const t = await localServer({}, { onRequest: () => outside });
    close = t.close;
    const r = await t.client.callTool(RISK);
    const s = r.structuredContent as { hint: string; free_tier: { this_route: boolean } };
    expect(s.free_tier.this_route).toBe(false);
    expect(s.hint).toContain("paiement_requis: this tool costs $0.10 per call.");
    expect(s.hint).toContain("Free API key, no card: not this route.");
    expect(s.hint).toContain("prepaid credits");
  });

  it("a free tool answers as the API sends it", async () => {
    const t = await localServer({}, { onRequest: () => dataReply({ suggestions: [] }) });
    close = t.close;
    const r = await t.client.callTool({ name: "suggest_company_names", arguments: { q: "dano" } });
    expect(r.structuredContent).toEqual({ payment_required: false, resultat: { suggestions: [] } });
    expect(r.isError).toBe(false);
  });
});
